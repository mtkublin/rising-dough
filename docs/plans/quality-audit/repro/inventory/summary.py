"""Aggregate every inventory/*.txt into inventory/SUMMARY.txt: rule counts and per-package counts."""
from __future__ import annotations

import re
from collections import Counter, defaultdict

from _common import OUT


def pkg(path: str) -> str:
    m = re.match(r"src/budget_planner/(web/routers|web/middleware|web|services|repositories|domain|db|adapters|cli)?/?", path)
    if m and m.group(1):
        return m.group(1)
    if path.startswith("src/budget_planner/"):
        return "root"
    if "templates" in path:
        return "templates"
    return "other"


def main() -> None:
    out: list[str] = ["# SUMMARY (generated by summary.py): rows per rule, and per package", ""]
    for p in sorted(OUT.glob("*.txt")):
        if p.name == "SUMMARY.txt":
            continue
        rules: Counter[str] = Counter()
        pk: defaultdict[str, Counter[str]] = defaultdict(Counter)
        for line in p.read_text().splitlines():
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split("\t")
            if len(parts) < 3:
                continue
            rules[parts[1]] += 1
            pk[parts[1]][pkg(parts[0])] += 1
        out.append(f"## {p.stem} (total {sum(rules.values())})")
        for r, c in sorted(rules.items()):
            by = ", ".join(f"{k}={v}" for k, v in sorted(pk[r].items()))
            out.append(f"  {r:34s} {c:5d}   {by}")
        out.append("")
    (OUT / "SUMMARY.txt").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
