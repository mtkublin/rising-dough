#!/usr/bin/env bash
# scripts/dump_schema.sh — reproducible v2 schema snapshot generator.
#
# Builds a scratch SQLite DB by applying every migration up to a target
# version (default: 11, the last v2 migration before 0012_multi_user) and
# dumps the resulting schema to the fixture path. The dump is sorted and
# normalised so the file byte-shape is stable across runs on the same
# toolchain.
#
# Usage:
#   scripts/dump_schema.sh                             # default: through 0011 → tests/fixtures/v2_schema_snapshot.sql
#   scripts/dump_schema.sh --through 11 --out <path>   # explicit
#
# Prerequisites: `uv` + the project venv already created (`just install`).
# Idempotent: re-running overwrites the output file with identical bytes.

set -euo pipefail

THROUGH=11
OUT="tests/fixtures/v2_schema_snapshot.sql"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --through)
            THROUGH="$2"
            shift 2
            ;;
        --out)
            OUT="$2"
            shift 2
            ;;
        *)
            echo "unknown arg: $1" >&2
            exit 2
            ;;
    esac
done

TMP_DIR="$(mktemp -d -p "$(pwd)" .schema_dump.XXXXXX)"
trap 'rm -rf "$TMP_DIR"' EXIT

uv run python - "$THROUGH" "$TMP_DIR" "$OUT" <<'PY'
"""Build scratch DB through a target migration version, dump schema."""
from __future__ import annotations

import sys
from pathlib import Path

from budget_planner.config import Settings
from budget_planner.db.connection import get_connection
from budget_planner.db.migrate import MIGRATIONS_DIR, apply_migrations, discover

through = int(sys.argv[1])
tmp = Path(sys.argv[2])
out = Path(sys.argv[3])

staging = tmp / "migrations_subset"
staging.mkdir(parents=True, exist_ok=True)
for mig in discover(MIGRATIONS_DIR):
    if mig.version <= through:
        (staging / mig.filename).write_bytes(mig.sql.encode("utf-8"))

db_path = tmp / "scratch.sqlite"
if db_path.exists():
    db_path.unlink()
settings = Settings(_env_file=None, database_url=f"sqlite:///{db_path.as_posix()}")
conn = get_connection(settings)
apply_migrations(conn, staging)

# Deterministic order: tables alphabetical, then their indices alphabetical.
rows = conn.execute(
    "SELECT type, name, tbl_name, sql FROM sqlite_master "
    "WHERE sql IS NOT NULL "
    "ORDER BY tbl_name, "
    "CASE type WHEN 'table' THEN 1 WHEN 'index' THEN 2 ELSE 3 END, "
    "name"
).fetchall()
conn.close()

header = (
    "-- tests/fixtures/v2_schema_snapshot.sql\n"
    "-- Auto-generated by scripts/dump_schema.sh. Do not edit by hand.\n"
    f"-- Snapshot of the schema produced by applying migrations 0001..00{through:02d}.\n"
    "-- Baseline for `tests/integration/db/test_migrations.py::test_0012_*`.\n"
    "-- `schema_migrations` rows (migration ledger inserts) and `sqlite_sequence`\n"
    "-- entries are intentionally stripped: the fixture rehydrates schema shape\n"
    "-- only, not ledger state.\n"
    "\n"
)

body_lines: list[str] = []
for r in rows:
    name = r["name"]
    # Strip SQLite's internal sqlite_sequence / internal autoindex entries.
    if name.startswith("sqlite_"):
        continue
    body_lines.append(f"{r['sql']};")

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header + "\n".join(body_lines) + "\n", encoding="utf-8")
print(f"[dump_schema] wrote {out} ({len(body_lines)} objects, through migration 00{through:02d})")
PY
