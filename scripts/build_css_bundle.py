"""Inline the Rising Dough CSS @import list into one bundle (ADR-0107 §3).

``rd/css/main.css`` holds the layer order and ``@import url(x) layer(y)`` lines;
this writes ``rd/css/app.bundle.css`` with each import inlined, in order, as
``@layer y { ... }``. Deterministic; ``--check`` exits 1 when the bundle is stale.
Dev utility; never imported by the web app.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Callable
from pathlib import Path

CSS_DIR = Path(__file__).resolve().parent.parent / "src/budget_planner/web/static/rd/css"
ENTRY = "main.css"
BUNDLE = "app.bundle.css"

_IMPORT = re.compile(
    r"""^@import\s+url\(\s*["']?(?P<path>[^"')]+)["']?\s*\)\s*(?:layer\((?P<layer>[\w.-]+)\))?\s*;\s*$"""
)
_ANY_IMPORT = re.compile(r"@import\b")
_HEADER = "/* GENERATED by scripts/build_css_bundle.py from main.css; do not edit. */\n"


class BundleError(ValueError):
    """The entry stylesheet or an imported file cannot be bundled."""


def build_bundle(entry_text: str, read: Callable[[str], str]) -> str:
    """Return the bundle text; ``read`` maps an import path to that file's text."""
    parts: list[str] = [_HEADER]
    for line in entry_text.splitlines():
        stripped = line.strip()
        if _ANY_IMPORT.match(stripped):
            match = _IMPORT.match(stripped)
            if match is None:
                raise BundleError(f"unsupported @import form: {stripped}")
            path = match.group("path")
            body = read(path)
            if _ANY_IMPORT.search(body):
                raise BundleError(f"nested @import in {path} is not supported")
            body = body.rstrip("\n")
            layer = match.group("layer")
            parts.append(f"\n/* {path} */\n")
            parts.append(f"@layer {layer} {{\n{body}\n}}\n" if layer else f"{body}\n")
        elif stripped:
            parts.append(f"{line}\n")
    return "".join(parts)


def build_dir(css_dir: Path) -> str:
    """Bundle text for the css directory (entry ``main.css``)."""
    entry = (css_dir / ENTRY).read_text(encoding="utf-8")
    return build_bundle(entry, lambda rel: (css_dir / rel).read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the bundle is stale")
    parser.add_argument("--css-dir", type=Path, default=CSS_DIR)
    args = parser.parse_args(argv)
    target = args.css_dir / BUNDLE
    try:
        text = build_dir(args.css_dir)
    except (BundleError, OSError) as exc:
        print(f"build_css_bundle: {exc}", file=sys.stderr)
        return 2
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != text:
            print(f"{target} is stale; run `just css`", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
