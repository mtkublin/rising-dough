"""Data overlay for the vendored design handoff (T-UR00b, ADR-0147 section 4).

``tests/visual/handoff_overlay.toml`` corrects handoff values the seed cannot
produce. The vendored files stay byte-identical; the correction is applied when
a page is served (reference rendering in ``tests/visual/handoff.py`` and
``--target=mockup`` in ``tests/e2e/mockup_target.py``), through the one handler
returned by ``overlay_handler``.

Row format (``[[row]]``):

* ``page``      glob over the handoff-relative path (``fnmatch``: ``*`` also
  crosses ``/``), e.g. ``pages/*.html`` or ``pages/overlays/shortcuts.html``.
* ``exclude``   optional list of globs removed from ``page``.
* ``select``    CSS selector (soupsieve) addressing the element; it is only
  read, never changed.
* ``field``     ``text`` (the element's own text node equal to ``old``), one
  allowed attribute (``ALLOWED_ATTRIBUTES``) or ``class`` (ADR-0147 amendment 2026-11-25
  "class tokens and absent attributes": ``old`` and ``value`` are the whole class string and
  may differ only by a pair in ``ALLOWED_CLASS_CHANGES``).
* ``old``       exact current value; a stale row is an error.
* ``value``     replacement.
* ``count``     elements the selector must match per page (default 1).
* ``optional``  pages with zero matches are skipped (default false); the row
  must still match at least one page.
* ``reason``    required.
* ``absent``    ``true``: the attribute ``field`` does not exist on the element and the row
  sets it (``old`` must be ``""``). Only ``ABSENT_SETTABLE`` text attributes.
* ``source``    ``"geometry"`` marks chart rows generated by the app's geometry
  functions (``geometry_rows``, T-UR12); never hand-written in the toml file.

Chart geometry (T-UR12): ``geometry_rows`` walks the app's own chart fragment (rendered from
the seed) in step with the handoff's chart and emits one ``source = "geometry"`` row per
coordinate, label or tooltip text that differs. A structural difference (another tag, class
or number of elements) is an error: the seed, not the overlay, must carry that data.
"""

from __future__ import annotations

import fnmatch
import functools
import http.server
import re
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final
from urllib.parse import unquote, urlsplit

from bs4 import BeautifulSoup, Tag
from bs4.element import AttributeValueList, NavigableString

OVERLAY_FILE: Final = Path(__file__).with_name("handoff_overlay.toml")
ALLOWED_ATTRIBUTES: Final = frozenset(
    {
        "aria-label",
        "title",
        "value",
        "datetime",
        "aria-keyshortcuts",
        "data-digits",
        "data-marks",
        "data-signs",
    }
)
# Text attributes a row may CREATE (``absent = true``): what a form control shows. Never an id,
# class, style or structural attribute.
ABSENT_SETTABLE: Final = frozenset({"value", "placeholder"})
# Class changes a row may make, as (token removed, token added; "" = none). Each pair is a handoff
# inconsistency whose app side is right; a class change moves paint, not layout, and only these
# reviewed pairs are allowed.
#   rd-fc__net--negative -> none: the handoff's Dec 2026 forecast net cell paints a positive
#   figure (597.07 after the value row, forecast.monthly_projection) in the loss colour; the app
#   paints a positive net plain.
ALLOWED_CLASS_CHANGES: Final[frozenset[tuple[str, str]]] = frozenset({("rd-fc__net--negative", "")})
ALLOWED_CLASS_TOKENS: Final = frozenset(t for pair in ALLOWED_CLASS_CHANGES for t in pair if t)
GEOMETRY_ATTRIBUTES: Final = frozenset(
    {"d", "points", "x", "y", "width", "height", "cx", "cy", "r", "x1", "x2", "y1", "y2"}
)  # x1..y2: gridlines, ticks and guides move with the nice axis (T-UR12)
GEOMETRY_SOURCES: Final[frozenset[str]] = frozenset({"geometry"})
# Rows whose new value is the app's own computed text (T-UR00b, ADR-0147 amendment): the Plan ·
# analytics "vs 12-mo avg" cells. Generated by ``delta_rows`` from the app run over the seed and
# drift-tested like geometry rows; text only, the arrow and the ``--down`` class stay the handoff's.
APP_VALUES_SOURCE: Final = "app-values"
VALUE_SOURCES: Final[frozenset[str]] = frozenset({APP_VALUES_SOURCE})
ANALYTICS_PAGE: Final = "pages/plan/analytics.html"
GEOMETRY_TOLERANCE: Final = 0.06  # coordinates are compared to one decimal (handoff precision)


class OverlayError(ValueError):
    """A row is malformed, stale or ambiguous."""


@dataclass(frozen=True)
class Row:
    page: str
    select: str
    field: str
    old: str
    value: str
    reason: str
    exclude: tuple[str, ...] = ()
    count: int = 1
    optional: bool = False
    source: str = ""
    absent: bool = False

    def applies_to(self, page: str) -> bool:
        return fnmatch.fnmatchcase(page, self.page) and not any(
            fnmatch.fnmatchcase(page, g) for g in self.exclude
        )


def _row(raw: dict[str, Any]) -> Row:
    return Row(
        page=raw["page"],
        select=raw["select"],
        field=raw["field"],
        old=raw["old"],
        value=raw["value"],
        reason=raw.get("reason", ""),
        exclude=tuple(raw.get("exclude", ())),
        count=int(raw.get("count", 1)),
        optional=bool(raw.get("optional", False)),
        source=raw.get("source", ""),
        absent=bool(raw.get("absent", False)),
    )


@functools.cache
def load_rows(path: Path = OVERLAY_FILE) -> tuple[Row, ...]:
    with path.open("rb") as handle:
        return tuple(_row(r) for r in tomllib.load(handle).get("row", []))


def class_change_violation(old: str, value: str) -> str:
    """Why a class change is not allowed ("" = allowed): only a pair of the allow-list."""
    before, after = old.split(), value.split()
    removed = tuple(t for t in before if t not in after)
    added = tuple(t for t in after if t not in before)
    if len(removed) > 1 or len(added) > 1:
        return f"class change {old!r} -> {value!r} replaces more than one token"
    pair = (removed[0] if removed else "", added[0] if added else "")
    if pair not in ALLOWED_CLASS_CHANGES:
        return f"class token change {pair!r} is not in ALLOWED_CLASS_CHANGES"
    return ""


def kind_violation(row: Row) -> str:
    """Why a class or absent-attribute row breaks the ADR-0147 limits ("" = fine)."""
    if row.field == "class":
        if row.absent:
            return "a class row cannot be absent"
        return class_change_violation(row.old, row.value)
    if row.absent:
        if row.field not in ABSENT_SETTABLE:
            return f"attribute {row.field!r} cannot be created (only {sorted(ABSENT_SETTABLE)})"
        if row.old != "":
            return 'an absent row has old = ""'
    return ""


def _own_text(el: Tag, old: str) -> list[NavigableString]:
    return [c for c in el.children if type(c) is NavigableString and str(c) == old]


def _set_attribute(page: str, row: Row, el: Tag) -> None:
    """Apply one class, absent-attribute or attribute row to ``el`` (stale values raise)."""
    if row.field == "class":
        current = " ".join(el.get("class") or [])
        if current != row.old:
            raise OverlayError(f"{page}: {row.select!r} class={current!r}, expected {row.old!r}")
        el["class"] = AttributeValueList(row.value.split())
    elif row.absent:
        if el.get(row.field) is not None:
            raise OverlayError(
                f"{page}: {row.select!r} {row.field}={el.get(row.field)!r} exists, "
                "expected it absent"
            )
        el[row.field] = row.value
    else:
        if el.get(row.field) != row.old:
            raise OverlayError(
                f"{page}: {row.select!r} {row.field}={el.get(row.field)!r}, expected {row.old!r}"
            )
        el[row.field] = row.value


def apply_rows(page: str, html: str, rows: Sequence[Row]) -> str:
    """Return ``html`` with every row that applies to ``page`` applied.

    Pages no row applies to come back untouched (same string).
    """
    todo = [r for r in rows if r.applies_to(page)]
    if not todo:
        return html
    soup = BeautifulSoup(html, "html.parser")
    for row in todo:
        if message := kind_violation(row):
            raise OverlayError(f"{page}: {row.select!r}: {message}")
        found = soup.select(row.select)
        if not found and row.optional:
            continue
        if len(found) != row.count:
            raise OverlayError(
                f"{page}: {row.select!r} matched {len(found)} elements, expected {row.count}"
            )
        for el in found:
            if row.field == "text":
                nodes = _own_text(el, row.old)
                if len(nodes) != 1:
                    raise OverlayError(
                        f"{page}: {row.select!r} has {len(nodes)} text nodes equal to {row.old!r}"
                    )
                nodes[0].replace_with(row.value)
            else:
                _set_attribute(page, row, el)
    return str(soup)


_TOKEN = re.compile(r"[A-Za-z]|-?\d+(?:\.\d+)?")
_COMPARED = ALLOWED_ATTRIBUTES | GEOMETRY_ATTRIBUTES
# Attributes the app adds on purpose where the handoff markup has none, per element selector.
# derived.md "Deviations", row "`charts/forecast` scroll container": keyboard access for the
# 375 px sideways scroll. Only these, only on that element; every other mismatch still raises.
APP_ONLY_ATTRIBUTES: Final[dict[str, frozenset[str]]] = {
    "div.rd-chart-card__plot": frozenset({"tabindex", "role", "aria-label"}),
}


def same_geometry(old: str, new: str) -> bool:
    """True when two coordinate strings differ only in number formatting (``72.0`` / ``72.000``)."""
    left, right = _TOKEN.findall(old), _TOKEN.findall(new)
    if len(left) != len(right) or not left:
        return old == new
    for a, b in zip(left, right, strict=True):
        if a.isalpha() or b.isalpha():
            if a != b:
                return False
        elif abs(float(a) - float(b)) > GEOMETRY_TOLERANCE:
            return False
    return True


def _children(el: Tag) -> list[Tag]:
    return [c for c in el.children if isinstance(c, Tag)]


def _only_text(el: Tag) -> NavigableString | None:
    """The element's single non-blank text node when it has no child tags."""
    if _children(el):
        return None
    nodes = [c for c in el.children if type(c) is NavigableString and str(c).strip()]
    return nodes[0] if len(nodes) == 1 else None


def _diff(old: Tag, new: Tag, path: str, page: str, reason: str) -> list[Row]:
    """Rows turning ``old`` (handoff) into ``new`` (app); the structure must match."""
    if old.name != new.name or old.get("class") != new.get("class"):
        raise OverlayError(f"{page}: {path}: <{old.name}> differs structurally from <{new.name}>")
    found: list[tuple[str, str, str]] = []
    derived = frozenset().union(
        *(attrs for selector, attrs in APP_ONLY_ATTRIBUTES.items() if new.css.match(selector))
    )
    for name in sorted(_COMPARED & (set(old.attrs) | set(new.attrs))):
        before, after = old.get(name), new.get(name)
        if name in derived and before is None:
            continue
        if not isinstance(before, str) or not isinstance(after, str):
            raise OverlayError(f"{page}: {path}: attribute {name!r} is missing on one side")
        if before != after and not (name in GEOMETRY_ATTRIBUTES and same_geometry(before, after)):
            found.append((name, before, after))
    before_text, after_text = _only_text(old), _only_text(new)
    if (before_text is None) != (after_text is None):
        raise OverlayError(f"{page}: {path}: a text node on one side only")
    if before_text is not None and after_text is not None and str(before_text) != str(after_text):
        found.append(("text", str(before_text), str(after_text)))
    rows = [
        Row(page, path, field, before, after, reason, source="geometry")
        for field, before, after in found
    ]
    kids_old, kids_new = _children(old), _children(new)
    if len(kids_old) != len(kids_new):
        raise OverlayError(
            f"{page}: {path}: {len(kids_old)} child elements, the app draws {len(kids_new)}"
        )
    for i, (a, b) in enumerate(zip(kids_old, kids_new, strict=True), start=1):
        rows += _diff(a, b, f"{path} > :nth-child({i})", page, reason)
    return rows


def geometry_rows(
    page: str, pristine_html: str, *, root: str, app_html: str, reason: str
) -> tuple[Row, ...]:
    """Rows that make the handoff chart under ``root`` equal the app's chart (``app_html``)."""
    old = BeautifulSoup(pristine_html, "html.parser").select_one(root)
    new = BeautifulSoup(app_html, "html.parser").select_one(root)
    if old is None or new is None:
        side = "handoff" if old is None else "app"
        raise OverlayError(f"{page}: {root!r} not found in the {side} markup")
    return tuple(_diff(old, new, root, page, reason))


def delta_rows(
    pristine_html: str, app_deltas: Sequence[tuple[str, bool]], *, reason: str
) -> tuple[Row, ...]:
    """Rows turning the handoff's spend-table delta cells into the app's (text, ``app-values``).

    ``app_deltas`` is the app's ``(delta_text, delta_down)`` per category row, in order. A row
    count or an up/down mismatch is an error: the seed, not the overlay, carries that data.
    """
    soup = BeautifulSoup(pristine_html, "html.parser")
    cells = [tr.select_one(".rd-spend__delta") for tr in soup.select("tr.rd-row--spend")]
    if len(cells) != len(app_deltas):
        raise OverlayError(
            f"{ANALYTICS_PAGE}: {len(cells)} spend rows, the app has {len(app_deltas)}"
        )
    rows: list[Row] = []
    for i, (cell, (text, down)) in enumerate(zip(cells, app_deltas, strict=True), start=1):
        if cell is None or _only_text(cell) is None:
            raise OverlayError(f"{ANALYTICS_PAGE}: spend row {i} has no delta text")
        if ("rd-spend__delta--down" in (cell.get("class") or [])) != down:
            raise OverlayError(f"{ANALYTICS_PAGE}: spend row {i} differs in up/down from the app")
        old = str(_only_text(cell))
        if old != text:
            select = f"tr.rd-row--spend:nth-of-type({i}) .rd-spend__delta"
            rows.append(
                Row(ANALYTICS_PAGE, select, "text", old, text, reason, source=APP_VALUES_SOURCE)
            )
    return tuple(rows)


FORECAST_PAGE: Final = "pages/plan/forecast.html"
FORECAST_CHART_ROOT: Final = "figure.rd-chart-card"


def overlay_page(page: str, html: str) -> str:
    """Apply the committed overlay file to one handoff page."""
    return apply_rows(page, html, load_rows())


def overlay_handler(root: Path) -> type[http.server.SimpleHTTPRequestHandler]:
    """Static handler for ``root`` that serves HTML pages through the overlay."""
    resolved = root.resolve()

    class Handler(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *args: Any, **kwargs: Any) -> None:
            super().__init__(*args, directory=str(resolved), **kwargs)

        def log_message(self, format: str, *args: Any) -> None:
            return

        def do_GET(self) -> None:
            rel = unquote(urlsplit(self.path).path).lstrip("/")
            target = (resolved / rel).resolve()
            if target.suffix == ".html" and target.is_file() and resolved in target.parents:
                body = overlay_page(
                    target.relative_to(resolved).as_posix(),
                    target.read_text(encoding="utf-8"),
                ).encode()
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
                return
            super().do_GET()

    return Handler
