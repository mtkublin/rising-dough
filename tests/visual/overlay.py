"""Data overlay for the vendored design handoff (T-UR00b, ADR-0147 section 4).

``tests/visual/handoff_overlay.toml`` corrects handoff values the seed cannot
produce. The vendored files stay byte-identical; the correction is applied when
a page is served (reference rendering in ``tests/visual/handoff.py`` and
``--target=mockup`` in ``tests/e2e/mockup_target.py``), through the one handler
returned by ``overlay_handler``.

Row format (``[[row]]``):

* ``page``      glob over the handoff-relative path (``fnmatch``: ``*`` also
  crosses ``/``), e.g. ``pages/*.html`` or ``pages/overlays/shortcuts.html``.
* ``exclude``   optional list of globs removed from ``page``.
* ``select``    CSS selector (soupsieve) addressing the element; it is only
  read, never changed.
* ``field``     ``text`` (the element's own text node equal to ``old``) or one
  allowed attribute (``ALLOWED_ATTRIBUTES``).
* ``old``       exact current value; a stale row is an error.
* ``value``     replacement.
* ``count``     elements the selector must match per page (default 1).
* ``optional``  pages with zero matches are skipped (default false); the row
  must still match at least one page.
* ``reason``    required.
* ``source``    ``"geometry"`` is reserved for chart rows generated by the
  app's geometry function (T-UR12); refused until that exists.
"""

from __future__ import annotations

import fnmatch
import functools
import http.server
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final
from urllib.parse import unquote, urlsplit

from bs4 import BeautifulSoup, Tag
from bs4.element import NavigableString

OVERLAY_FILE: Final = Path(__file__).with_name("handoff_overlay.toml")
ALLOWED_ATTRIBUTES: Final = frozenset(
    {
        "aria-label",
        "title",
        "value",
        "datetime",
        "aria-keyshortcuts",
        "data-digits",
        "data-marks",
        "data-signs",
    }
)
GEOMETRY_ATTRIBUTES: Final = frozenset(
    {"d", "points", "x", "y", "width", "height", "cx", "cy", "r"}
)
GEOMETRY_SOURCES: Final[frozenset[str]] = frozenset()  # T-UR12 adds its generators here


class OverlayError(ValueError):
    """A row is malformed, stale or ambiguous."""


@dataclass(frozen=True)
class Row:
    page: str
    select: str
    field: str
    old: str
    value: str
    reason: str
    exclude: tuple[str, ...] = ()
    count: int = 1
    optional: bool = False
    source: str = ""

    def applies_to(self, page: str) -> bool:
        return fnmatch.fnmatchcase(page, self.page) and not any(
            fnmatch.fnmatchcase(page, g) for g in self.exclude
        )


def _row(raw: dict[str, Any]) -> Row:
    return Row(
        page=raw["page"],
        select=raw["select"],
        field=raw["field"],
        old=raw["old"],
        value=raw["value"],
        reason=raw.get("reason", ""),
        exclude=tuple(raw.get("exclude", ())),
        count=int(raw.get("count", 1)),
        optional=bool(raw.get("optional", False)),
        source=raw.get("source", ""),
    )


@functools.cache
def load_rows(path: Path = OVERLAY_FILE) -> tuple[Row, ...]:
    with path.open("rb") as handle:
        return tuple(_row(r) for r in tomllib.load(handle).get("row", []))


def _own_text(el: Tag, old: str) -> list[NavigableString]:
    return [c for c in el.children if type(c) is NavigableString and str(c) == old]


def apply_rows(page: str, html: str, rows: Sequence[Row]) -> str:
    """Return ``html`` with every row that applies to ``page`` applied.

    Pages no row applies to come back untouched (same string).
    """
    todo = [r for r in rows if r.applies_to(page)]
    if not todo:
        return html
    soup = BeautifulSoup(html, "html.parser")
    for row in todo:
        found = soup.select(row.select)
        if not found and row.optional:
            continue
        if len(found) != row.count:
            raise OverlayError(
                f"{page}: {row.select!r} matched {len(found)} elements, expected {row.count}"
            )
        for el in found:
            if row.field == "text":
                nodes = _own_text(el, row.old)
                if len(nodes) != 1:
                    raise OverlayError(
                        f"{page}: {row.select!r} has {len(nodes)} text nodes equal to {row.old!r}"
                    )
                nodes[0].replace_with(row.value)
            else:
                if el.get(row.field) != row.old:
                    raise OverlayError(
                        f"{page}: {row.select!r} {row.field}={el.get(row.field)!r}, "
                        f"expected {row.old!r}"
                    )
                el[row.field] = row.value
    return str(soup)


def overlay_page(page: str, html: str) -> str:
    """Apply the committed overlay file to one handoff page."""
    return apply_rows(page, html, load_rows())


def overlay_handler(root: Path) -> type[http.server.SimpleHTTPRequestHandler]:
    """Static handler for ``root`` that serves HTML pages through the overlay."""
    resolved = root.resolve()

    class Handler(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *args: Any, **kwargs: Any) -> None:
            super().__init__(*args, directory=str(resolved), **kwargs)

        def log_message(self, format: str, *args: Any) -> None:
            return

        def do_GET(self) -> None:
            rel = unquote(urlsplit(self.path).path).lstrip("/")
            target = (resolved / rel).resolve()
            if target.suffix == ".html" and target.is_file() and resolved in target.parents:
                body = overlay_page(
                    target.relative_to(resolved).as_posix(),
                    target.read_text(encoding="utf-8"),
                ).encode()
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
                return
            super().do_GET()

    return Handler
